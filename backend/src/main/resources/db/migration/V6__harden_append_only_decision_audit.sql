create or replace function require_demo_capability_hashes()
returns trigger
language plpgsql
as $$
begin
    if new.customer_capability_hash is null
       or new.staff_capability_hash is null
       or new.customer_capability_hash = new.staff_capability_hash then
        raise exception 'new demo sessions require distinct capability hashes';
    end if;
    return new;
end;
$$;

create trigger trg_demo_session_capability_hashes
before insert or update of customer_capability_hash, staff_capability_hash on demo_session
for each row execute function require_demo_capability_hashes();

