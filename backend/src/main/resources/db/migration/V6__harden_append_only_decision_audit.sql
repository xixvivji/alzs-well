create or replace function reject_decision_audit_mutation()
returns trigger
language plpgsql
as $$
begin
    raise exception 'decision_audit is append-only';
end;
$$;

create trigger trg_decision_audit_append_only
before update or delete on decision_audit
for each row execute function reject_decision_audit_mutation();

